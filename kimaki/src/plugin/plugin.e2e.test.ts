// The bot registers the Kimaki plugin by writing plugins/kimaki/index.js into
// the global OpenCode config dir (opencode-server.ts installPluginShim). The
// test server starts with an empty config dir and a location that is already
// loaded, so the plugin arrives through OpenCode's watcher reload, like for a
// user whose service runs before the first Kimaki start.

import { afterAll, beforeAll, expect, test } from 'bun:test'
import fs from 'node:fs'
import path from 'node:path'

import type { BotHandle } from '../main.ts'
import {
  seedProjectChannel,
  startOpencodeTestServer,
  startTestBot,
  startTwin,
  tempDataDir,
  TEST_USER_ID,
  waitFor,
  waitForFooter,
  warmUp,
  type OpencodeTestServer,
  type TestTwin,
} from '../test/harness.ts'

let server: OpencodeTestServer
let twin: TestTwin
let bot: BotHandle
let dataDir: string

beforeAll(async () => {
  dataDir = tempDataDir()
  ;[server, twin] = await Promise.all([startOpencodeTestServer(), startTwin()])
  await warmUp({ server })
  await seedProjectChannel({
    dataDir,
    channelId: twin.channelId,
    guildId: twin.discord.guildId,
    directory: server.projectDirectory,
  })
}, 60_000)

afterAll(async () => {
  await bot?.stop()
  await twin?.stop()
  await server?.stop()
  fs.rmSync(dataDir, { recursive: true, force: true })
})

test('bot start writes the plugin shim, OpenCode loads it, a restart does not rewrite it', async () => {
  const shim = path.join(server.configDir, 'plugins', 'kimaki', 'index.js')
  expect(fs.existsSync(shim)).toBe(false)
  const client = await server.client()
  const pluginStatus = async (id: string) => {
    const plugins = await client.plugin.list({ location: { directory: server.projectDirectory } })
    return plugins.data.find((plugin) => plugin.id === id)?.state.status ?? 'missing'
  }
  const kimakiStatus = () => pluginStatus('kimaki')
  expect(await kimakiStatus()).toBe('missing')
  // Shim of Kimaki 1.0.0; the session ID line now lives in the kimaki plugin.
  const legacyShim = path.join(server.configDir, 'plugins', 'kimaki-session-id')
  fs.mkdirSync(legacyShim, { recursive: true })
  fs.writeFileSync(path.join(legacyShim, 'index.js'), 'export default undefined\n')

  bot = await startTestBot({ dataDir, twin, server })
  expect(fs.existsSync(legacyShim)).toBe(false)
  expect(fs.readFileSync(shim, 'utf8').replace(/file:\/\/\S+\/dist\//, 'file:///<kimaki>/dist/'))
    .toMatchInlineSnapshot(`
    "// Generated by Kimaki on bot start. Loads the plugin of the running Kimaki install.
    export { default } from "file:///<kimaki>/dist/plugin/index.js"
    "
  `)
  // No wait here: the first session must itself wait until OpenCode's watcher loads the shim.
  await twin.discord.channel(twin.channelId).user(TEST_USER_ID).sendMessage({ content: 'plugin shim turn' })
  const thread = await twin.discord.channel(twin.channelId).waitForThread({ timeout: 8_000 })
  await waitForFooter({ discord: twin.discord, threadId: thread.id })
  expect(await kimakiStatus()).toBe('active')
  // Plugin setup registers the bot's MCP server for this location.
  const mcpStatus = await waitFor({
    label: 'the teetee MCP server',
    check: async () => {
      const servers = await client.mcp.list({ location: { directory: server.projectDirectory } })
      const status = servers.data.find((entry) => entry.name === 'teetee')?.status.status
      return status === 'connected' ? status : null
    },
  })
  expect(mcpStatus).toBe('connected')
  expect(await pluginStatus('kimaki-session-id')).toBe('missing')
  expect(await twin.discord.thread(thread.id).text()).toMatchInlineSnapshot(`
    "--- from: user (tommy)
    plugin shim turn
    --- from: assistant (TestBot)
    -# *using deterministic-provider/deterministic-v2 ⋅ build*
    ok
    -# *project ⋅ main ⋅ Ns ⋅ deterministic-v2*"
  `)

  const written = fs.statSync(shim).mtimeMs
  await bot.stop()
  bot = await startTestBot({ dataDir, twin, server })
  expect(fs.statSync(shim).mtimeMs).toBe(written)
}, 30_000)
